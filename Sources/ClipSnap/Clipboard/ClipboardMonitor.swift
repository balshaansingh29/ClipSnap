import AppKit
import CryptoKit

/// Polls NSPasteboard.changeCount (the same approach Maccy uses; macOS has no
/// pasteboard change notification) and records new clips.
@MainActor
final class ClipboardMonitor: ObservableObject {
    @Published var paused = false

    private let store: ClipStore
    private let settings = AppSettings.shared
    private var timer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var suppressedChangeCount: Int?

    /// Pasteboard types that mark a copy as secret or machine-generated.
    private let ignoredTypes: Set<String> = [
        "org.nspasteboard.TransientType",
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "net.antelle.keeweb",
        "Pasteboard generator type",
    ]

    init(store: ClipStore) { self.store = store }

    func start() {
        timer?.invalidate()
        let t = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
        t.tolerance = 0.15
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    /// Call right after we write to the pasteboard ourselves so the write isn't re-recorded.
    func suppressCurrentChange() {
        suppressedChangeCount = NSPasteboard.general.changeCount
    }

    private func poll() {
        let pb = NSPasteboard.general
        let count = pb.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count

        if suppressedChangeCount == count { return }
        if paused { return }

        let types = Set((pb.types ?? []).map(\.rawValue))
        if !types.isDisjoint(with: ignoredTypes) { return }

        let app = NSWorkspace.shared.frontmostApplication
        if let id = app?.bundleIdentifier, settings.excludedApps.contains(id) { return }

        if let text = pb.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let item = ClipItem(kind: .text, text: text,
                                sourceBundleID: app?.bundleIdentifier,
                                sourceName: app?.localizedName,
                                date: Date(), key: "t:" + text)
            store.add(item, rtf: pb.data(forType: .rtf))
            return
        }

        if settings.captureImages, let png = pngData(from: pb) {
            let digest = SHA256.hash(data: png).map { String(format: "%02x", $0) }.joined()
            var dims: String?
            if let rep = NSBitmapImageRep(data: png) { dims = "\(rep.pixelsWide)×\(rep.pixelsHigh)" }
            let item = ClipItem(kind: .image, imageDimensions: dims,
                                sourceBundleID: app?.bundleIdentifier,
                                sourceName: app?.localizedName,
                                date: Date(), key: "i:" + digest)
            store.add(item, png: png)
        }
    }

    private func pngData(from pb: NSPasteboard) -> Data? {
        if let png = pb.data(forType: .png) { return png }
        guard let tiff = pb.data(forType: .tiff),
              let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }
}
